"""Measured answers to the Chapter 10 exercises -> tables/numbers_ch10_exercises.tex (run with PYTHONPATH=rom_engine/src:rom_engine/examples)."""
import os, sys
import numpy as np
from scipy.linalg import eigh
HERE = os.path.dirname(os.path.abspath(__file__)); TAB = os.path.join(HERE, "..", "tables")
from greedy_frequency_training import build_damped_cantilever
from rom_engine import FrequencyROM, build_pod_basis_from_frf_snapshots, greedy_train_frequency_basis
from rom_engine.scm import SingularValueLowerBound, certified_error_bound
from rom_engine.scm_lp import LPSingularValueLowerBound, certified_error_bound as lp_cert

NUM = {}
def num(k, v): NUM[k] = v
def sci(x):
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"

def setup(n):
    sysobj, alpha, beta = build_damped_cantilever(n=n)
    free = np.asarray(sysobj.free_dofs); ix = np.ix_(free, free)
    K, M, C = sysobj.K[ix], sysobj.M[ix], sysobj.C[ix]
    lam = eigh(K, M, eigvals_only=True); wn = np.sqrt(lam)
    F_full = np.zeros(sysobj.n_dof); F_full[sysobj.n_dof - 2] = 1000.0
    return sysobj, alpha, beta, free, K, M, C, wn, F_full[free], F_full

# ---------------- Exercise 1: seeds
sysobj, alpha, beta, free, K, M, C, wn, F, F_full = setup(20); w1 = wn[0]
band = np.linspace(0.1, 20.0, 400) * w1
rng = np.random.default_rng(0)
test_near = np.concatenate([wn[i] * (1.0 + 0.05 * rng.standard_normal(20)) for i in range(3)]); test_near = test_near[test_near > 0]
cache = {}
def truth(om):
    if om not in cache: cache[om] = sysobj.solve_harmonic(om, F_full)[free]
    return cache[om]
def maxerr(rom):
    return max(np.linalg.norm(rom.frequency_response([om], F)[0] - truth(om)) / np.linalg.norm(truth(om)) for om in test_near)
for ns in (3, 4):
    for r in (5, 6):
        gb, hist = greedy_train_frequency_basis(band, M, K, F, rayleigh=(alpha, beta), n_seed=ns, tol=1e-12, max_modes=r)
        rom = FrequencyROM.from_MCK(M, K, gb.V, rayleigh=(alpha, beta))
        picks = ", ".join(f"{h[0] / w1:.1f}" for h in hist[:r])
        ub = build_pod_basis_from_frf_snapshots(np.linspace(band[0], band[-1], gb.n_modes), M, K, F, C=C, n_modes=gb.n_modes)
        ru = FrequencyROM.from_MCK(M, K, ub.V, rayleigh=(alpha, beta))
        tag = f"Seed{'Three' if ns == 3 else 'Four'}{'Five' if r == 5 else 'Six'}"
        num(f"cfrEx{tag}Picks", picks); num(f"cfrEx{tag}Err", sci(maxerr(rom))); num(f"cfrEx{tag}Unif", sci(maxerr(ru)))
        print(ns, r, picks, maxerr(rom), maxerr(ru), flush=True)

# ---------------- Exercise 2: 4-element beam
grid = np.linspace(0.1, 20.0, 200)
cand = np.linspace(0.1, 20.0, 300)
n20K = np.linalg.norm(K, 2)
s4, a4, b4, f4, K4, M4, C4, wn4, F4, Ff4 = setup(4); w4 = wn4[0]
n4K = np.linalg.norm(K4, 2)
num("cfrExKRatio", f"{n20K / n4K:.0f}"); num("cfrExKFour", sci(n4K)); num("cfrExNFree", str(len(f4)))
band4 = np.linspace(0.1, 20.0, 400) * w4
gb, _ = greedy_train_frequency_basis(band4, M4, K4, F4, rayleigh=(a4, b4), n_seed=3, tol=1e-12, max_modes=5)
rom = FrequencyROM.from_MCK(M4, K4, gb.V, rayleigh=(a4, b4))
g4 = grid * w4
e4 = np.array([np.linalg.norm(rom.frequency_response([om], F4)[0] - s4.solve_harmonic(om, Ff4)[f4]) for om in g4])
for nm, B, fn in (("Lip", SingularValueLowerBound, certified_error_bound), ("Lp", LPSingularValueLowerBound, lp_cert)):
    bd = B.from_affine(rom.affine); bd.greedy_train(cand * w4, tol=0.05, max_references=15)
    cb = np.array([fn(rom, bd, om, F4) for om in g4]); fin = np.isfinite(cb)
    num(f"cfrEx{nm}Refs", str(len(bd.reference_omegas))); num(f"cfrEx{nm}Finite", str(int(fin.sum())))
    num(f"cfrEx{nm}Ratio", f"{np.median(cb[fin] / e4[fin]):.0f}" if fin.any() else "0")
    print(nm, len(bd.reference_omegas), fin.sum(), np.median(cb[fin] / e4[fin]) if fin.any() else None, flush=True)

# ---------------- Exercise 4: RMS under doubled damping
def rms(sc):
    fq = np.linspace(0.1 * w1 / (2 * np.pi), 20.0 * w1 / (2 * np.pi), 6000)
    tip = len(free) - 2; S = np.empty(len(fq))
    for i, f in enumerate(fq):
        om = 2 * np.pi * f
        A = -om ** 2 * M + 1j * om * sc * (alpha * M + beta * K) + K
        S[i] = abs(np.linalg.solve(A, F)[tip]) ** 2
    return np.sqrt(np.trapezoid(S, fq))
r1, r2 = rms(1.0), rms(2.0)
num("cfrExRmsOne", f"{r1:.4e}"); num("cfrExRmsRatio", f"{r2 / r1:.3f}"); num("cfrExRmsInvSqrt", f"{1 / np.sqrt(2):.3f}")
print("rms", r1, r2, r2 / r1, flush=True)
