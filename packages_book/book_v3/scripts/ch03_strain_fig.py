"""
ch03_strain_fig.py -- Figure of Section 3.1.1 (kinematics): strain is what is left of a displacement field after rigid motion is removed.

Four displacement fields on the unit square, u = G x with a constant displacement gradient G = grad u:
  (a) stretch in x, (b) simple shear, (c) small rigid rotation, (d) pure shear = the symmetric part of (b).
For each panel the strain eps = sym(G) and the rotation w = skew(G) are computed from G, not typed, and printed under the panel.
The squares are drawn with the displacement field itself (the linear theory), so panel (c) is a rotation by the small-rotation field.

Writes: figures/ch03_strain.pdf, tables/numbers_ch03_strain.tex
Run from the book directory:   python scripts/ch03_strain_fig.py
"""
__author__ = "Abhijeet <abhijeetshandilya19@gmail.com>"
import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Polygon

HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
FIG, TAB = os.path.join(BOOK, "figures"), os.path.join(BOOK, "tables")
BLUE, ORANGE, GREY = "#2b6cb0", "#dd8a2f", "0.45"
a = 0.25                                       # size of the displacement gradient (drawn large enough to see)

G = {"stretch": np.array([[a, 0.0], [0.0, 0.0]]),
     "shear": np.array([[0.0, a], [0.0, 0.0]]),
     "rotation": np.array([[0.0, -a], [a, 0.0]]),
     "pure shear": np.array([[0.0, a / 2], [a / 2, 0.0]])}
titles = ["(a) stretch", "(b) simple shear", "(c) rigid rotation", "(d) pure shear"]


def main():
    fig, axs = plt.subplots(1, 4, figsize=(7.4, 2.45))
    nums = {}
    for ax, (name, g), title in zip(axs, G.items(), titles):
        eps = 0.5 * (g + g.T); w = 0.5 * (g[1, 0] - g[0, 1])           # symmetric part; rotation = skew part
        gam = 2.0 * eps[0, 1]                                          # engineering shear strain
        for k in np.linspace(0, 1, 5):                                 # grid lines before
            ax.plot([k, k], [0, 1], color="0.75", lw=0.6, ls=(0, (3, 2))); ax.plot([0, 1], [k, k], color="0.75", lw=0.6, ls=(0, (3, 2)))
        ax.add_patch(Polygon([[0, 0], [1, 0], [1, 1], [0, 1]], closed=True, fc="none", ec="0.55", lw=0.9, ls=(0, (3, 2))))
        s = np.linspace(0, 1, 5)
        for k in s:                                                    # grid lines after: x + G x
            for pts in (np.array([[k, t] for t in s]), np.array([[t, k] for t in s])):
                q = pts + pts @ g.T
                ax.plot(q[:, 0], q[:, 1], color=ORANGE, lw=0.7)
        cor = np.array([[0, 0], [1, 0], [1, 1], [0, 1]], float); cq = cor + cor @ g.T
        ax.add_patch(Polygon(cq, closed=True, fc=ORANGE, alpha=0.10, ec=ORANGE, lw=1.4))
        for p, q in zip(cor, cq):
            if np.linalg.norm(q - p) > 1e-12:
                ax.annotate("", xy=q, xytext=p, arrowprops=dict(arrowstyle="-|>", color=BLUE, lw=0.9, mutation_scale=6, shrinkA=0, shrinkB=0))
        ax.set_xlim(-0.4, 1.5); ax.set_ylim(-0.2, 1.4); ax.set_aspect("equal"); ax.axis("off")
        ax.set_title(title, fontsize=8)
        ax.text(0.62, -0.30, rf"$\varepsilon_x={eps[0, 0]:.2f}$  $\varepsilon_y={eps[1, 1]:.2f}$", ha="center", va="top", fontsize=6.6, transform=ax.transData)
        ax.text(0.62, -0.50, rf"$\gamma_{{xy}}={gam:.2f}$  $\omega={w:.3f}$".replace("0.250", "0.25"), ha="center", va="top", fontsize=6.6)
        nums[name] = (eps[0, 0], eps[1, 1], gam, w)
    for ax in axs:
        ax.set_ylim(-0.78, 1.4)
    fig.tight_layout(w_pad=0.4)
    fig.savefig(os.path.join(FIG, "ch03_strain.pdf"), bbox_inches="tight"); plt.close(fig)
    # the decomposition of the simple shear into pure shear and a rotation is exact for the gradient
    sh, ps, ro = G["shear"], G["pure shear"], G["rotation"]
    resid = np.max(np.abs(sh - (ps + (-0.5) * ro)))
    with open(os.path.join(TAB, "numbers_ch03_strain.tex"), "w") as fh:
        fh.write("% generated by scripts/ch03_strain_fig.py -- do not edit\n")
        fh.write(f"\\newcommand{{\\ckStrainA}}{{{a:.2f}\\xspace}}\n")
        fh.write(f"\\newcommand{{\\ckStrainRotEps}}{{{np.max(np.abs(0.5 * (G['rotation'] + G['rotation'].T))):.2g}\\xspace}}\n")
        fh.write(f"\\newcommand{{\\ckStrainShearGamma}}{{{nums['shear'][2]:.2f}\\xspace}}\n")
        fh.write(f"\\newcommand{{\\ckStrainShearOmega}}{{{nums['shear'][3]:.3f}\\xspace}}\n")
        fh.write(f"\\newcommand{{\\ckStrainDecompErr}}{{{resid:.1g}\\xspace}}\n")
    print("strains:", {k: tuple(round(float(x), 4) for x in v) for k, v in nums.items()}, "decomposition residual", resid)


if __name__ == "__main__":
    main()
