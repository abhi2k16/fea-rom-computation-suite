"""Static response of free-interface and Craig-Bampton models of the chain of Chapter 11 (Sec. 11.6.3, item C3).
Run: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_free_static.py
Writes figures/ch11_free_static.pdf and tables/numbers_ch11_free_static.tex (macro prefix ccm)."""
import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from rom_engine.cms import craig_bampton, free_interface_cms
plt.rcParams.update({"font.size": 8, "axes.grid": True, "grid.alpha": 0.3})
NUM = {}
def sci(x):
    if x == 0: return "0"
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"
K, M = a.chain(); n = 40; iface = [39, 20]
F = np.zeros(n); F[39] = 1.0
uref = np.linalg.solve(K, F)
w2, V = eigh(K, M)
fig, ax = plt.subplots(1, 2, figsize=(6.2, 2.6), constrained_layout=True, sharey=True)
names = {3: "Three", 10: "Ten"}
for j, nm in enumerate((3, 10)):
    out = {}
    cb = craig_bampton(K, M, iface, nm); out["cb"] = cb.T @ np.linalg.solve(cb.K, cb.T.T @ F)
    for meth in ("rubin", "macneal"):
        m = free_interface_cms(K, M, iface, nm, meth); out[meth] = m.T @ np.linalg.solve(m.K, m.T.T @ F)
    Vm = V[:, :nm]; out["modal"] = Vm @ np.linalg.solve(Vm.T @ K @ Vm, Vm.T @ F)
    x = np.arange(n) + 1
    ax[j].plot(x, uref / uref[39], "k-", lw=2.4, alpha=0.35, label="exact")
    ax[j].plot(x, out["cb"] / uref[39], "C0--", lw=1.2, label="Craig--Bampton, Rubin")
    ax[j].plot(x, out["macneal"] / uref[39], "C3-", lw=1.2, label="modal, MacNeal")
    for i in iface: ax[j].axvline(i + 1, color="0.6", ls=":", lw=0.8)
    ax[j].set_title(f"$n_m={nm}$", loc="left", fontsize=8); ax[j].set_xlabel("mass number")
    for k, v in out.items():
        NUM[f"ccmFs{names[nm]}{k.capitalize()}Prof"] = sci(np.linalg.norm(v - uref) / np.linalg.norm(uref))
    NUM[f"ccmFs{names[nm]}TipRatio"] = f"{out['modal'][39] / uref[39]:.3f}"
    NUM[f"ccmFs{names[nm]}MidRatio"] = f"{out['modal'][20] / uref[20]:.3f}"
    ax[j].legend(fontsize=6, loc="upper left")
ax[0].set_ylabel("displacement / exact tip displacement")
fig.savefig(os.path.join(FIG, "ch11_free_static.pdf")); fig.savefig("/tmp/ch11_free_static.png", dpi=140)
NUM["ccmFsMid"] = "21"; NUM["ccmFsTip"] = "40"
with open(os.path.join(TAB, "numbers_ch11_free_static.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_free_static.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
