"""Interface modes of the membrane of Chapter 11 (Sec. 11.3 and 11.5.2, item C6).
Run: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_iface_modes.py
Writes figures/ch11_iface_modes.pdf and tables/numbers_ch11_iface_modes.tex (macro prefix ccm)."""
import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh, subspace_angles
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from rom_engine.cms import craig_bampton
from rom_engine.interface_reduction import gram_schmidt_interface_modes
plt.rcParams.update({"font.size": 8, "axes.grid": True, "grid.alpha": 0.3})
NUM = {}
def sci(x):
    if x == 0: return "0"
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"
K, M, iface = a.membrane(16, 21)
nb = len(iface)
cb = craig_bampton(K, M, iface, 40)
lam, X = eigh(cb.K[:nb, :nb], cb.M[:nb, :nb])
w, V = eigh(K, M)
G = gram_schmidt_interface_modes([V], iface)
y = np.arange(1, nb + 1)
def norm(v):
    v = v / np.abs(v).max(); i = np.argmax(np.abs(v)); return v * np.sign(v[i])
fig, ax = plt.subplots(1, 3, figsize=(6.2, 2.8), constrained_layout=True)
for k in range(6):
    ax[0].plot(y, norm(X[:, k]), lw=1.1, label=f"{k + 1}")
    ax[1].plot(y, norm(G[:, k]), lw=1.1)
ax[0].set_title("(a) characteristic constraint modes", loc="left", fontsize=7); ax[1].set_title("(b) Gram--Schmidt modes", loc="left", fontsize=7)
for j in (0, 1): ax[j].set_xlabel("interface node")
ax[0].set_ylabel("value, scaled to peak 1"); ax[0].legend(fontsize=5.5, ncol=3, loc="upper center", bbox_to_anchor=(0.5, -0.28), title="mode", title_fontsize=5.5)
# (c) distance between the two subspaces and eigenvalues
ks = np.arange(1, 13)
dist = []
for k in ks:
    dist.append(float(np.sin(subspace_angles(X[:, :k], G[:, :k]).max())))
ax[2].semilogy(ks, np.maximum(dist, 1e-17), "o-", ms=3, color="C3")
ax[2].set_xlabel("number of modes $k$"); ax[2].set_ylabel("distance between the two subspaces"); ax[2].set_title("(c) the two bases", loc="left", fontsize=7)
ax[2].set_ylim(1e-17, 1e0)
fig.savefig(os.path.join(FIG, "ch11_iface_modes.pdf")); fig.savefig("/tmp/ch11_iface_modes.png", dpi=140)
words = ["One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight"]
for k in range(8): NUM[f"ccmIm{words[k]}"] = f"{lam[k]:.3f}"
NUM["ccmImLast"] = f"{lam[-1]:.2f}"
NUM["ccmImDistMax"] = sci(float(max(dist))); NUM["ccmImDistSix"] = sci(float(dist[5])); NUM["ccmImDistTwo"] = sci(float(dist[1]))
nsc = lambda v: int(np.sum(np.diff(np.sign(v[np.abs(v) > 1e-9])) != 0))
NUM["ccmImSignSix"] = str(nsc(X[:, 5])); NUM["ccmImSignOne"] = str(nsc(X[:, 0]))
with open(os.path.join(TAB, "numbers_ch11_iface_modes.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_iface_modes.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM); print(np.array(dist))
