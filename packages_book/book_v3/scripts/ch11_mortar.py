"""The mortar operator on the non-matching meshes of Chapter 11 (Sec. 11.3, item C4).
Run: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_mortar.py
Writes figures/ch11_mortar.pdf and tables/numbers_ch11_mortar.tex (macro prefix ccm)."""
import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from fea_engine.mortar import dual_mortar_operator
plt.rcParams.update({"font.size": 8})
NUM = {}
def sci(x):
    if x == 0: return "0"
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"
A, B = a.Grid(9, 9, 0.0, 1.0, "right"), a.Grid(9, 7, 1.0, 2.0, "left")
P, D, Mm = dual_mortar_operator(B.coords[B.interface], A.coords[A.interface])
yA, yB = A.coords[A.interface][:, 1], B.coords[B.interface][:, 1]
fig, ax = plt.subplots(1, 3, figsize=(6.2, 2.7), gridspec_kw={"width_ratios": [1.25, 0.9, 1.1]}, constrained_layout=True)
# (a) meshes, slave drawn with a gap
gap = 0.12
for G, shift, col, lab in ((A, 0.0, "C0", "master 9x9"), (B, gap, "C1", "slave 9x7")):
    nx = len(np.unique(G.coords[:, 0])); ny = len(np.unique(G.coords[:, 1]))
    X = G.coords[:, 0].reshape(nx, ny) + shift; Y = G.coords[:, 1].reshape(nx, ny)
    for i in range(nx): ax[0].plot(X[i], Y[i], color=col, lw=0.5)
    for j in range(ny): ax[0].plot(X[:, j], Y[:, j], color=col, lw=0.5)
    ii = (nx - 1) if col == "C0" else 0
    ax[0].plot(X[ii], Y[ii], "o" if col == "C0" else "s", color=col, ms=3.5, label=f"{lab}, {ny} interface nodes")
ax[0].set_aspect("equal"); ax[0].set_xticks([]); ax[0].set_yticks([]); ax[0].legend(fontsize=5.5, loc="upper center", bbox_to_anchor=(0.5, -0.02), ncol=1)
ax[0].set_title("(a) the two meshes", loc="left", fontsize=8)
# (b) P
im = ax[1].imshow(P, cmap="RdBu_r", vmin=-1, vmax=1, aspect="auto")
ax[1].set_xlabel("master node (9)"); ax[1].set_ylabel("slave node (7)")
ax[1].set_xticks(range(0, 9, 2)); ax[1].set_xticklabels(range(1, 10, 2)); ax[1].set_yticks(range(0, 7, 2)); ax[1].set_yticklabels(range(1, 8, 2))
ax[1].set_title("(b) $\\boldsymbol{P}$", loc="left", fontsize=8)
fig.colorbar(im, ax=ax[1], shrink=0.7, pad=0.03)
# (c) a smooth master field copied by P and by the nearest node
g = np.sin(np.pi * yA); ex = np.sin(np.pi * yB)
nn = np.array([g[np.argmin(np.abs(yA - y))] for y in yB])
yy = np.linspace(0, 1, 200)
ax[2].plot(yy, np.sin(np.pi * yy), "k-", lw=2.0, alpha=0.3, label="field")
ax[2].plot(yA, g, "o", color="C0", ms=3.5, label="master values")
ax[2].plot(yB, P @ g, "s", color="C1", ms=3.5, label="slave, $\\boldsymbol{P}$")
ax[2].plot(yB, nn, "x", color="C3", ms=4, label="slave, nearest node")
ax[2].set_xlabel("position along the interface"); ax[2].set_title("(c) transferring a field", loc="left", fontsize=8)
ax[2].legend(fontsize=5.5, loc="lower center"); ax[2].grid(alpha=0.3)
fig.savefig(os.path.join(FIG, "ch11_mortar.pdf")); fig.savefig("/tmp/ch11_mortar.png", dpi=140)
NUM["ccmMorMaster"] = str(len(yA)); NUM["ccmMorSlave"] = str(len(yB)); NUM["ccmMorNnz"] = str(int((P != 0).sum()))
NUM["ccmMorRowSum"] = sci(float(np.abs(P.sum(1) - 1).max())); NUM["ccmMorMinEntry"] = f"{P.min():.3f}"
NUM["ccmMorAffine"] = sci(float(np.linalg.norm(P @ yA - yB)))
NUM["ccmMorErrP"] = sci(float(np.linalg.norm(P @ g - ex) / np.linalg.norm(ex)))
NUM["ccmMorErrNear"] = sci(float(np.linalg.norm(nn - ex) / np.linalg.norm(ex)))
NUM["ccmMorRatio"] = f"{np.linalg.norm(nn - ex) / np.linalg.norm(P @ g - ex):.0f}"
with open(os.path.join(TAB, "numbers_ch11_mortar.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_mortar.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
