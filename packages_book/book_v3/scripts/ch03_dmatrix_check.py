"""
ch03_dmatrix_check.py -- checks behind the stress--strain figure of Section 3.1.2 (the isotropic D matrix).

For E = 210 GPa and several Poisson ratios it checks, against the package (fea_engine.material):
  * the 3-D matrix drawn in the figure equals D_solid3d, entry by entry;
  * the plane-stress matrix equals the 3-D matrix with sigma_z = 0 imposed (static condensation of the z row), and D_plane_stress;
  * the plane-strain matrix equals the in-plane block of the 3-D matrix, and D_plane_strain;
  * the shear entry of the 3-D matrix equals G = E / (2 (1 + nu));
  * D is positive definite for -1 < nu < 1/2 and loses definiteness at the ends (smallest eigenvalue of the 3-D matrix).
Writes tables/numbers_ch03_dmatrix.tex.   Run from the book directory:   python scripts/ch03_dmatrix_check.py
"""
__author__ = "Abhijeet <abhijeetshandilya19@gmail.com>"
import os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
for p in (os.path.join(BOOK, "..", "..", "fea_engine", "src"),):
    if os.path.isdir(p): sys.path.insert(0, os.path.abspath(p))
from fea_engine.material import Material, D_solid3d, D_plane_stress, D_plane_strain

E = 210e9
def fig3d(nu):
    c = E / ((1 + nu) * (1 - 2 * nu)); g = (1 - 2 * nu) / 2
    D = np.zeros((6, 6)); D[:3, :3] = nu; D[range(3), range(3)] = 1 - nu
    for i in range(3, 6): D[i, i] = g
    return c * D
def fig_ps(nu): return E / (1 - nu**2) * np.array([[1, nu, 0], [nu, 1, 0], [0, 0, (1 - nu) / 2]])
def fig_pe(nu):
    c = E / ((1 + nu) * (1 - 2 * nu)); return c * np.array([[1 - nu, nu, 0], [nu, 1 - nu, 0], [0, 0, (1 - 2 * nu) / 2]])
def condense_sz0(D6):
    idx = [0, 1, 3]; z = 2                                              # sigma_z = 0: eliminate eps_z
    A = D6[np.ix_(idx, idx)] - np.outer(D6[idx, z], D6[z, idx]) / D6[z, z]
    return A

nus = [-0.5, 0.0, 0.15, 0.3, 0.45, 0.49]
d3 = max(np.max(np.abs(fig3d(n) - D_solid3d(Material(E=E, nu=n)))) / E for n in nus)
dps = max(np.max(np.abs(fig_ps(n) - D_plane_stress(Material(E=E, nu=n)))) / E for n in nus)
dpe = max(np.max(np.abs(fig_pe(n) - D_plane_strain(Material(E=E, nu=n)))) / E for n in nus)
dcond = max(np.max(np.abs(condense_sz0(fig3d(n)) - fig_ps(n))) / E for n in nus)
dblock = max(np.max(np.abs(fig3d(n)[np.ix_([0, 1, 3], [0, 1, 3])] - fig_pe(n))) / E for n in nus)
dG = max(abs(fig3d(n)[3, 3] - E / (2 * (1 + n))) / E for n in nus)
grid = np.linspace(-0.99, 0.49, 149)
mineig = [np.min(np.linalg.eigvalsh(fig3d(n))) / E for n in grid]
allpos = all(m > 0 for m in mineig)
out_hi = np.min(np.linalg.eigvalsh(fig3d(0.6))) / E; out_lo = np.min(np.linalg.eigvalsh(fig3d(-1.5))) / E      # outside the range: not positive definite
lam_max = lambda n: np.max(np.linalg.eigvalsh(fig3d(n))) / E                                              # the volumetric (bulk) direction
lam_min = lambda n: np.min(np.linalg.eigvalsh(fig3d(n))) / E

def sci(x):
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$" if x != 0 else "0"
with open(os.path.join(BOOK, "tables", "numbers_ch03_dmatrix.tex"), "w") as fh:
    fh.write("% generated by scripts/ch03_dmatrix_check.py -- do not edit\n")
    def m(k, v): fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
    m("cdmDiffThreeD", sci(d3)); m("cdmDiffPS", sci(dps)); m("cdmDiffPE", sci(dpe)); m("cdmDiffCond", sci(dcond)); m("cdmDiffBlock", sci(dblock)); m("cdmDiffG", sci(dG))
    m("cdmAllPos", "yes" if allpos else "NO"); m("cdmNuLo", "-0.99"); m("cdmNuHi", "0.49")
    m("cdmEigOutHi", f"{out_hi:.2f}"); m("cdmEigOutLo", f"{out_lo:.2f}")
    m("cdmMaxEigA", f"{lam_max(0.3):.2f}"); m("cdmMaxEigB", f"{lam_max(0.49):.0f}"); m("cdmMaxEigC", f"{lam_max(0.499):.0f}")
    m("cdmMinEigB", f"{lam_min(0.49):.2f}")
print("3d", d3, "ps", dps, "pe", dpe, "condensation", dcond, "block", dblock, "G", dG, "all positive", allpos, "outside", out_hi, out_lo, "max eig", lam_max(0.3), lam_max(0.49), lam_max(0.499), "min eig .49", lam_min(0.49))
