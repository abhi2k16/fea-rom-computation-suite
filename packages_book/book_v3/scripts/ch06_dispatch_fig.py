"""
ch06_dispatch_fig.py -- Figure of Section 7.7 (time of solve_static with backend="scipy" and backend="auto") and its macros.

Reads tables/ch06_dispatch_data.json (n_free, t_scipy_ms, t_auto_ms), which ch01_assets.py writes after timing the solves,
and writes figures/ch06_dispatch.pdf and tables/numbers_ch06_dispatch.tex. Run on its own to replot stored data:
    python packages_book/book_v3/scripts/ch06_dispatch_fig.py
"""
import json, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
FIG, TAB = os.path.join(BOOK, "figures"), os.path.join(BOOK, "tables")
BLUE, ORG, GREY, NAVY = "#2f7fc1", "#d9822b", "#6b7785", "#1b3a5c"
THRESHOLD = 5000                                   # fea_engine.backend_dispatch.AUTO_DOF_THRESHOLD


def main():
    d = json.load(open(os.path.join(TAB, "ch06_dispatch_data.json")))
    nf, ts, ta = (np.array(d[k], float) for k in ("n_free", "t_scipy_ms", "t_auto_ms"))
    ex = ta - ts
    fit = np.polyfit(np.log(nf[1:]), np.log(ex[1:]), 1)
    loc = np.diff(np.log(ex)) / np.diff(np.log(nf))
    num = {"cdeDispLocA": f"{loc[0]:.1f}", "cdeDispLocB": f"{loc[1]:.1f}", "cdeDispLocC": f"{loc[2]:.1f}",
           "cdeDispLocD": f"{loc[3]:.1f}", "cdeDispProbeRatio": f"{ex[-1] / ts[-1]:.1f}"}
    with open(os.path.join(TAB, "numbers_ch06_dispatch.tex"), "w") as fh:
        fh.write("% generated by scripts/ch06_dispatch_fig.py -- do not edit\n")
        for k, v in num.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8, "pdf.fonttype": 42})
    fig, ax = plt.subplots(1, 2, figsize=(7.0, 3.0))
    a = ax[0]
    a.loglog(nf, ts, "o-", color=BLUE, lw=1.6, ms=4, label="backend='scipy'")
    a.loglog(nf, ta, "s--", color=ORG, lw=1.6, ms=4, label="backend='auto'")
    a.axvline(THRESHOLD, color=GREY, ls=":", lw=1); a.axvspan(THRESHOLD, 9000, color="#eeeeee", lw=0)
    a.text(5400, 1.5, "above 5 000\nauto would pick\ntorch (not run)", fontsize=6.5, color=GREY, va="bottom")
    a.set_xlim(100, 9000); a.set_ylim(0.8, 1000); a.set_xticks([100, 1000]); a.set_xticklabels(["10$^2$", "10$^3$"])
    a.set_xlabel("free degrees of freedom"); a.set_ylabel("time of solve_static (ms)")
    a.legend(frameon=False, fontsize=7, loc="upper left")
    a.set_title("(a) time of the solve", fontsize=8, fontweight="bold", loc="left", color=NAVY)
    a.grid(alpha=0.25, which="both", lw=0.4)
    b = ax[1]
    b.loglog(nf, ex, "o-", color=ORG, lw=1.6, ms=4, label="extra time of 'auto'")
    xx = np.array([300, nf[-1]])
    b.loglog(xx, np.exp(fit[1]) * xx ** fit[0], "-", color=GREY, lw=0.9, label=f"fitted slope {fit[0]:.1f}")
    b.loglog(xx, ex[-1] * (xx / nf[-1]) ** 3, "--", color=GREY, lw=0.9, label="slope 3 (dense Cholesky)")
    b.set_xlim(100, 9000); b.set_ylim(0.3, 1500); b.set_xticks([100, 1000]); b.set_xticklabels(["10$^2$", "10$^3$"])
    b.set_xlabel("free degrees of freedom"); b.set_ylabel("extra time (ms)")
    b.legend(frameon=False, fontsize=6.5, loc="upper left")
    b.annotate(f"{ex[-1] / ts[-1]:.0f}$\\times$ the solve", (nf[-1], ex[-1]), (700, 90), fontsize=6.5, color=ORG,
               arrowprops=dict(arrowstyle="-", color=ORG, lw=0.7))
    b.set_title("(b) cost of the probe", fontsize=8, fontweight="bold", loc="left", color=NAVY)
    b.grid(alpha=0.25, which="both", lw=0.4)
    for x in ax:
        for s in ("top", "right"):
            x.spines[s].set_visible(False)
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "ch06_dispatch.pdf")); plt.close(fig)
    return num, fit[0]


if __name__ == "__main__":
    print(main())
