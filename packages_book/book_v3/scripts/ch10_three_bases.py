"""Relative state error against frequency of the 5-column greedy, uniform and modal bases (Chapter 10, Sec. 10.8, Q14).
Run with PYTHONPATH=rom_engine/src:rom_engine/examples.  Writes figures/ch10_three_bases.pdf and tables/numbers_ch10_three_bases.tex."""
import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
from greedy_frequency_training import build_damped_cantilever
from rom_engine import FrequencyROM, build_pod_basis_from_frf_snapshots, greedy_train_frequency_basis

sysobj, alpha, beta = build_damped_cantilever(n=20)
free = np.asarray(sysobj.free_dofs); ix = np.ix_(free, free)
K, M, C = sysobj.K[ix], sysobj.M[ix], sysobj.C[ix]
lam, Vm = eigh(K, M); wn = np.sqrt(lam); w1 = wn[0]
F_full = np.zeros(sysobj.n_dof); F_full[sysobj.n_dof - 2] = 1000.0; F = F_full[free]
band = np.linspace(0.1, 20.0, 400) * w1
r = 5
gb, hist = greedy_train_frequency_basis(band, M, K, F, rayleigh=(alpha, beta), n_seed=3, tol=1e-12, max_modes=r)
ub = build_pod_basis_from_frf_snapshots(np.linspace(band[0], band[-1], gb.n_modes), M, K, F, C=C, n_modes=gb.n_modes)
roms = {"greedy": FrequencyROM.from_MCK(M, K, gb.V, rayleigh=(alpha, beta)),
        "uniform": FrequencyROM.from_MCK(M, K, ub.V, rayleigh=(alpha, beta)),
        "modal": FrequencyROM.from_MCK(M, K, Vm[:, :r], rayleigh=(alpha, beta))}
grid = np.unique(np.concatenate([np.linspace(0.1, 20.0, 700) * w1] + [wn[i] * (1 + np.linspace(-0.06, 0.06, 240)) for i in range(3)]))
truth = [sysobj.solve_harmonic(om, F_full)[free] for om in grid]
err = {k: np.array([np.linalg.norm(rm.frequency_response([om], F)[0] - u) / np.linalg.norm(u) for om, u in zip(grid, truth)]) for k, rm in roms.items()}
seeds = np.linspace(band[0], band[-1], 3) / w1
picks = np.array([h[0] for h in hist]) / w1
unif = np.linspace(band[0], band[-1], gb.n_modes) / w1
fig, ax = plt.subplots(figsize=(6.2, 3.0), constrained_layout=True)
x = grid / w1
ax.semilogy(x, err["greedy"], "C1-", lw=1.1, label="greedy")
ax.semilogy(x, err["uniform"], "C0-", lw=1.1, label="uniform")
ax.semilogy(x, err["modal"], "C2-", lw=1.1, label="modal")
for w in wn[:3] / w1: ax.axvline(w, color="0.55", ls=":", lw=0.8)
ax.plot(np.concatenate([seeds, picks]), np.full(len(seeds) + len(picks), 3e-11), "v", color="C1", ms=5, label="greedy snapshots")
ax.plot(unif, np.full(len(unif), 1e-11), "^", color="C0", ms=5, label="uniform snapshots")
ax.set_xlabel("$\\omega/\\omega_1$"); ax.set_ylabel("relative state error"); ax.set_ylim(5e-12, 3)
ax.legend(fontsize=6, ncol=2, loc="lower right", bbox_to_anchor=(1.0, 0.10))
fig.savefig(os.path.join(FIG, "ch10_three_bases.pdf"))
fig.savefig("/tmp/ch10_three_bases.png", dpi=130)
above = err["greedy"] > err["uniform"]
last_below = x[np.where(~above)[0].max()]          # last frequency at which greedy is not worse than uniform
nums = {"cfrTbCross": f"{last_below:.1f}", "cfrTbGreedyAt": f"{x[np.argmax(err['greedy'])]:.1f}", "cfrTbUniformAt": f"{x[np.argmax(err['uniform'])]:.1f}",
        "cfrTbModalMed": f"{np.median(err['modal']):.0e}".replace("e-0", "e-").replace("e-", "\\times10^{-") + "}"}
with open(os.path.join(TAB, "numbers_ch10_three_bases.tex"), "w") as fh:
    fh.write("% generated by scripts/ch10_three_bases.py -- do not edit\n")
    for k, v in nums.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v if k != "cfrTbModalMed" else "$" + v + "$"))
print(nums)
print({k: (v.max(), x[np.argmax(v)]) for k, v in err.items()})
