"""Run Listing 8.2 of Chapter 8 (lst:pod-try) and write its printed output and the numbers quoted around it.

The code is read from chapters/ch08.tex, so the printed output cannot drift from the listed code. Also computes
(i) the same sweep with a basis built from snapshots of the tip load alone (no random load variation), and
(ii) the singular values of the snapshots of Listing 8.1 relative to the first.
Writes tables/ch08_try_out.txt and tables/numbers_ch08_try.tex.
"""
import io, os, re, sys, contextlib, warnings
import numpy as np
warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE); ROOT = os.path.abspath(os.path.join(BOOK, "..", ".."))
sys.path[:0] = [ROOT, os.path.join(ROOT, "rom_engine", "examples")]
from rom_engine import PodBasis, AffineDecomposition                                    # noqa: E402
from rom_engine.sampling import optimal_lhs                                             # noqa: E402
src = open(os.path.join(BOOK, "chapters", "ch08.tex"), encoding="utf-8").read()
asrc = open(os.path.join(HERE, "ch08_assets.py"), encoding="utf-8").read()
cn = [int(x) for x in re.search(r"COST_NSNAP, COST_MODES, COST_NQUERY, COST_NREASM = (\d+), (\d+), (\d+), (\d+)", asrc).groups()]


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


m = re.search(r"\\begin\{lstlisting\}\[[^\]]*label=\{lst:pod-try\}\]\n(.*?)\\end\{lstlisting\}", src, re.S)
g = {"__name__": "__listing__"}
buf = io.StringIO()
with contextlib.redirect_stdout(buf):
    exec(compile(m.group(1), "lst:pod-try", "exec"), g)
open(os.path.join(BOOK, "tables", "ch08_try_out.txt"), "w", encoding="utf-8").write(buf.getvalue())
print(buf.getvalue())

K1, K2, F, tip, mus, full = g["K1"], g["K2"], g["F"], g["tip"], g["mus"], np.array(g["full"])
rng = np.random.default_rng(0)
S = np.column_stack([np.linalg.solve(a * K1 + b * K2, F) for a, b in 0.5 + 4.5 * rng.uniform(size=(10, 2))])
V = PodBasis().fit(S, n_modes=10).V
aff = AffineDecomposition([K1, K2], lambda mu: [mu[0], mu[1]]).project(V)
Fr = V.T @ F
clean = np.array([(V @ np.linalg.solve(aff.assemble_reduced(mu), Fr))[tip] for mu in mus])
err_clean = np.max(np.abs(clean - full) / np.abs(full))
sv = PodBasis().fit(np.column_stack([np.linalg.solve(a[0] * K1 + a[1] * K2, F) for a in 0.5 + 4.5 * optimal_lhs(cn[0], 2, rng=np.random.default_rng(0))]), n_modes=cn[1]).singular_values
red = np.array(g["red"])
NUM = {"cpdTrySpeed": f"{g['t_full'] / g['t_red']:.0f}", "cpdTryErr": sci(g["err"]), "cpdTryErrClean": sci(err_clean),
       "cpdTipSvTwo": f"{sv[1] / sv[0]:.2f}", "cpdTipSvThree": sci(sv[2] / sv[0]),
       "cpdCostNSnap": str(cn[0]), "cpdCostModes": str(cn[1]), "cpdCostNQuery": str(cn[2]), "cpdCostNReasm": str(cn[3])}
with open(os.path.join(BOOK, "tables", "numbers_ch08_try.tex"), "w") as fh:
    fh.write("% generated by scripts/ch08_listings.py -- do not edit\n")
    for k, v in NUM.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
print(NUM)
