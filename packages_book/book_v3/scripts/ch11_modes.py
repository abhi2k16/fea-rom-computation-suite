"""Constraint modes and fixed-interface modes of one half of the Chapter 11 beam (Sec. 11.3, item C1).
Run: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_modes.py
Writes figures/ch11_modes.pdf and tables/numbers_ch11_modes.tex (macro prefix ccm)."""
import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from rom_engine.cms import craig_bampton
plt.rcParams.update({"font.size": 8, "axes.grid": True, "grid.alpha": 0.3})
NUM = {}
def sci(x):
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"

NEL = a.NEL
fr, K, M = a.beam(1.0, 2 * NEL, [0, 2 * NEL]); w2, Vf = eigh(K, M)
frL, KL, ML = a.beam(0.5, NEL, [0])
ib = [int(np.where(frL == 2 * NEL)[0][0]), int(np.where(frL == 2 * NEL + 1)[0][0])]
nm = 5
cb = craig_bampton(KL, ML, ib, nm)
T = cb.T
vi = np.arange(0, KL.shape[0], 2)                       # transverse unknowns of nodes 1..NEL of the half (node NEL is the cut)
x = np.arange(1, NEL + 1) * 0.5 / NEL
xx = np.concatenate([[0.0], x])
tr = lambda col: np.concatenate([[0.0], col[vi]])         # deflection at x = 0 (clamp) and the nodes
psi_v, psi_th = T[:, 0], T[:, 1]
fig, ax = plt.subplots(1, 3, figsize=(6.2, 2.5), constrained_layout=True)
ax[0].plot(xx * 1e3, tr(psi_v), "C0-", lw=1.3, label="unit deflection")
ax[0].plot(xx * 1e3, tr(psi_th) * 1e3 / 1e3 * 10, "C1-", lw=1.3, label="unit rotation, $\\times10$")
ax[0].set_title("(a) constraint modes", loc="left", fontsize=8)
ax[0].set_xlabel("position along the half (mm)"); ax[0].set_ylabel("deflection"); ax[0].set_ylim(-0.9, 1.7); ax[0].legend(fontsize=6, loc="upper left")
for k in range(3):
    s = T[:, 2 + k]; s = s / np.abs(s[vi]).max() * np.sign(s[vi][np.argmax(np.abs(s[vi]))])
    ax[1].plot(xx * 1e3, tr(s), lw=1.2, label=f"mode {k + 1}, {cb.freq_fixed_hz[k]:.0f} Hz")
ax[1].set_title("(b) fixed-interface modes", loc="left", fontsize=8); ax[1].set_xlabel("position along the half (mm)"); ax[1].set_ylim(-1.1, 2.0); ax[1].legend(fontsize=6, loc="upper left")
# (c) decomposition of the exact first mode of the beam in the Craig-Bampton basis of the half
pos_full = {d: i for i, d in enumerate(fr)}
u = np.array([Vf[pos_full[d], 0] for d in frL])           # left half of exact mode 1
ub = u[ib]
iint = cb.internal
Psi = T[iint, :2]; Phi = T[iint, 2:]
Mii = ML[np.ix_(iint, iint)]
eta = Phi.T @ Mii @ (u[iint] - Psi @ ub)
u_static = np.zeros_like(u); u_static[iint] = Psi @ ub; u_static[ib] = ub
u_modal = np.zeros_like(u); u_modal[iint] = Phi @ eta
u_cb = u_static + u_modal
sc = np.abs(u[vi]).max()
ax[2].plot(xx * 1e3, tr(u) / sc, "k-", lw=2.0, alpha=0.5, label="exact mode 1")
ax[2].plot(xx * 1e3, tr(u_static) / sc, "C0--", lw=1.2, label="constraint part")
ax[2].plot(xx * 1e3, tr(u_modal) / sc * 10, "C3-", lw=1.2, label="fixed-interface part, $\\times10$")
ax[2].set_title("(c) exact beam mode 1", loc="left", fontsize=8); ax[2].set_xlabel("position along the half (mm)"); ax[2].set_ylim(-0.05, 1.6); ax[2].legend(fontsize=6, loc="upper left")
fig.savefig(os.path.join(FIG, "ch11_modes.pdf")); fig.savefig("/tmp/ch11_modes.png", dpi=140)
err_static = np.linalg.norm(u - u_static) / np.linalg.norm(u); err_cb = np.linalg.norm(u - u_cb) / np.linalg.norm(u)
NUM["ccmModesFixOne"] = f"{cb.freq_fixed_hz[0]:.0f}"; NUM["ccmModesFixTwo"] = f"{cb.freq_fixed_hz[1]:.0f}"; NUM["ccmModesFixThree"] = f"{cb.freq_fixed_hz[2]:.0f}"
NUM["ccmModesInternal"] = str(len(iint)); NUM["ccmModesInterface"] = str(len(ib))
NUM["ccmModesStaticErr"] = sci(err_static); NUM["ccmModesCbErr"] = sci(err_cb)
NUM["ccmModesModalShare"] = f"{100 * np.linalg.norm(u_modal) / np.linalg.norm(u):.1f}"
NUM["ccmModesRotMax"] = f"{np.abs(psi_th[vi]).max():.3f}"
with open(os.path.join(TAB, "numbers_ch11_modes.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_modes.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
