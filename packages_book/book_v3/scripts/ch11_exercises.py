"""Measured answers to the exercises of Chapter 11 (audit item U14).
Run from the repository root: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_exercises.py
Writes tables/numbers_ch11_exercises.tex (macro prefix ccmEx, no digits in names)."""
import os, importlib.util, time
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from fea_engine.solver import FESystem
from fea_engine.geometry import generate_mesh
from fea_engine import elements
from fea_engine.material import EI_beam, Section
from fea_engine.mortar import MortarTie2D
from rom_engine.cms import couple, craig_bampton, reduce_interface
from rom_engine.component_pod import ReducedAssembly
from rom_engine.interface_reduction import natural_frequency_errors
NUM = {}
def sci(x):
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"
# ---- Exercise 1: the beam split into three parts (10, 20, 10 elements) with two interfaces
fr, K, M = a.beam(1.0, 2 * a.NEL, [0, 2 * a.NEL]); f_full = a.freqs_hz(K, M, 4)
pos = lambda f_, d: int(np.where(f_ == d)[0][0])
f1, K1, M1 = a.beam(0.25, 10, [0]); f3, K3_, M3 = a.beam(0.25, 10, [10])
sy = FESystem(generate_mesh(dim=1, L=0.5, n=20), elements.Beam2DEulerBernoulli())
sy.assemble_stiffness(EI_beam(a.MAT, Section(A=a.A_SEC, I=a.I_SEC))); sy.assemble_mass(a.RHO * a.A_SEC)
f2 = np.arange(42); K2, M2 = np.array(sy.K), np.array(sy.M)
i1 = [pos(f1, 20), pos(f1, 21)]; i2 = [pos(f2, 0), pos(f2, 1), pos(f2, 40), pos(f2, 41)]; i3 = [pos(f3, 0), pos(f3, 1)]
res, prev, mono = {}, None, True
for nm in (1, 2, 3, 5, 10, 20):
    cp = couple([craig_bampton(K1, M1, i1, nm), craig_bampton(K2, M2, i2, nm), craig_bampton(K3_, M3, i3, nm)], [[0, 1], [0, 1, 2, 3], [2, 3]])
    e = float(np.max(np.abs(np.asarray(cp.solve_modal(4)[0]) - f_full) / f_full)); res[nm] = (cp.K.shape[0], e)
    mono &= prev is None or e <= prev; prev = e
NUM["ccmExThreeMono"] = "yes" if mono else "no"
for nm, w in ((1, "One"), (5, "Five"), (20, "Twenty")):
    NUM[f"ccmExThreeErr{w}"] = sci(res[nm][1]); NUM[f"ccmExThreeSize{w}"] = str(res[nm][0])
NUM["ccmExThreeIface"] = str(len(i1))   # unknowns of one interface node pair; global interface is two nodes
NUM["ccmExThreeIface"] = str(2 * len(i1))
# ---- Exercise 2: first 40 frequencies, membrane, n_m = 40
Km, Mm, ifm = a.membrane(16, 21); cb = craig_bampton(Km, Mm, ifm, 40)
plain = np.abs(natural_frequency_errors(Km, Mm, cb.T, 40)).max()
kmin = next(k for k in range(1, len(ifm) + 1) if abs(np.abs(natural_frequency_errors(Km, Mm, reduce_interface(cb, k).T, 40)).max() - plain) <= 1e-6 * plain)
NUM["ccmExFortyPlain"] = sci(plain); NUM["ccmExFortyMinK"] = str(kmin); NUM["ccmExFortyRedundant"] = str(len(ifm) - kmin)
# ---- Exercises 4 and 5: component POD with 4u^3 and 8u^3, and timing
def setup(k3):
    a.K3 = k3
    A, B = a.Grid(9, 9, 0.0, 1.0, "right"), a.Grid(9, 7, 1.0, 2.0, "left"); na = A.n
    tie = MortarTie2D(na + B.interface, A.interface, np.vstack([A.coords, B.coords]), na + B.n, dofs_per_node=1)
    return A, B, tie
def reduced(k3, rank):
    A, B, tie = setup(k3); u_ref, resid, tang = a.full_solution(A, B, tie)
    ba, bb = a.make_basis(A, B, rank, rank); ra = ReducedAssembly(ba, bb, tie.P); r = ra.solve(resid, tang)
    return np.linalg.norm(r.u - u_ref) / np.linalg.norm(u_ref), r.iterations, r.converged, (A, B, tie, resid, tang, ra)
e4, it4, c4, ctx = reduced(4.0, 12); e8, it8, c8, _ = reduced(8.0, 12)
assert c4 and c8
NUM["ccmExFourErr"] = sci(e4); NUM["ccmExFourIters"] = str(it4); NUM["ccmExEightErr"] = sci(e8); NUM["ccmExEightIters"] = str(it8)
A, B, tie, resid, tang, ra12 = ctx
a.K3 = 4.0
def med(f, n=30):
    ts = []
    for _ in range(n):
        t0 = time.perf_counter(); f(); ts.append(time.perf_counter() - t0)
    return float(np.median(ts)) * 1e3
NUM["ccmExTimeFull"] = f"{med(lambda: a.full_solution(A, B, tie)):.0f}"
ba, bb = a.make_basis(A, B, 3, 3); ra3 = ReducedAssembly(ba, bb, tie.P)
NUM["ccmExTimeRankThree"] = f"{med(lambda: ra3.solve(resid, tang)):.1f}"; NUM["ccmExTimeRankTwelve"] = f"{med(lambda: ra12.solve(resid, tang)):.1f}"
with open(os.path.join(TAB, "numbers_ch11_exercises.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_exercises.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
