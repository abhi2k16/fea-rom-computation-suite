"""
ch06_probe_assets.py -- the symmetric-positive-definite test of backend="auto" on a free-floating plate (Section 7.7).

A plane-stress plate with no fixed degrees of freedom has a singular stiffness matrix (three rigid-body modes). The test of
fea_engine.backend_dispatch.select_backend is a Cholesky factorisation, which can succeed on such a matrix. This script
records (a) one case at a lowered threshold where the test accepts the singular matrix and (b) five sizes above the default
threshold where it rejects it. It writes tables/numbers_ch06_probe.tex. Run:   python packages_book/book_v3/scripts/ch06_probe_assets.py
"""
import inspect, os, sys, warnings
import numpy as np
warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(BOOK, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "fea_engine", "src"))
from fea_engine import FESystem
from fea_engine.material import Material, D_plane_stress
from fea_engine.mesh import rectangle_mesh
from fea_engine.elements import ELEMENT_REGISTRY
from fea_engine.backend_dispatch import select_backend, AUTO_DOF_THRESHOLD, _is_symmetric

NUM = {}
fmt = lambda n: f"{n:,}".replace(",", "\\,")
def sci(x):
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"

def free_block(nx, ny):
    mesh = rectangle_mesh(4.0, 1.0, nx, ny)
    s = FESystem(mesh, ELEMENT_REGISTRY["quad4_plane_stress"](), sparse=True)
    s.assemble_stiffness(D_plane_stress(Material(E=210e9, nu=0.3)))
    free = s.free_dofs
    return s._as_solve_matrix(s.K)[np.ix_(free, free)]

LOW = 10
K = free_block(32, 16)
backend, d = select_backend(K, dof_threshold=LOW)
w = np.linalg.eigvalsh(K.toarray())
assert d["spd"] and backend == "torch" and w[0] < 0          # accepted although the smallest eigenvalue is negative
NUM["cdeProbeN"] = fmt(d["n"]); NUM["cdeProbeLowThr"] = str(LOW)
NUM["cdeProbeMinEig"] = sci(w[0]); NUM["cdeProbeMaxEig"] = sci(w[-1])
ns = []
for nx, ny in ((70, 35), (72, 36), (74, 37), (76, 38), (80, 40)):
    Kb = free_block(nx, ny); b, dd = select_backend(Kb)
    assert dd["n"] > AUTO_DOF_THRESHOLD and not dd["spd"] and b == "scipy"
    ns.append(dd["n"])
NUM["cdeProbeRejLo"] = fmt(min(ns)); NUM["cdeProbeRejHi"] = fmt(max(ns))
NUM["cdeAutoThr"] = fmt(AUTO_DOF_THRESHOLD)
tol = inspect.signature(_is_symmetric).parameters["tol"].default
NUM["cdeSymTol"] = f"$10^{{{int(round(np.log10(tol)))}}}$"
with open(os.path.join(BOOK, "tables", "numbers_ch06_probe.tex"), "w") as fh:
    fh.write("% generated by scripts/ch06_probe_assets.py -- do not edit\n")
    for k, v in NUM.items(): fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
print(NUM)
