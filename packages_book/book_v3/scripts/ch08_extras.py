"""Chapter 8: results quoted in the text that no other script produces (tables/numbers_ch08_extra.tex)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import numpy as np
import ch08_assets as A
from rom_engine import PodBasis

b = A.Beam(A.N_ELEM)
S = b.snapshots(A.design(60, "olhs", 0)); test = A.design(40, "rand", 7)
pod = PodBasis().fit(S, n_modes=A.RANK_C); podM = PodBasis().fit(S, n_modes=A.RANK_C, M=b.M)
ge = [A.tip_err(b, pod.V[:, :r], test) for r in range(1, A.RANK_C + 1)]
gm = [A.tip_err(b, podM.V[:, :r], test) for r in range(1, A.RANK_C + 1)]
ratio = max(max(a / c, c / a) for a, c in zip(ge, gm))     # largest factor between Euclidean and mass-weighted Galerkin error
with open(os.path.join(A.BOOK, "tables", "numbers_ch08_extra.tex"), "w") as fh:
    fh.write("% generated by scripts/ch08_extras.py -- do not edit\n")
    fh.write(f"\\newcommand{{\\cpdMassRatioMax}}{{{ratio:.2f}\\xspace}}\n")
print(ratio)
