"""Chapter 9: the design constants quoted in the text, as macros (tables/numbers_ch09_const.tex).

Values come from the constants block of ch09_assets.py; the listings of ch09.tex are checked against them, and a
mismatch stops the run."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import ch09_assets as A

tex = open(os.path.join(A.BOOK if hasattr(A, "BOOK") else os.path.dirname(HERE), "chapters", "ch09.tex"), encoding="utf-8").read()
BOOK = os.path.dirname(HERE)


def need(rx, what):
    m = re.search(rx, tex)
    if not m:
        raise SystemExit(f"ch09_consts: cannot find {what} in the listings")
    return m.groups()


(n_el,) = need(r"generate_mesh\(dim=1, L=1\.0, n=(\d+)\)", "number of elements")
al, be = need(r"RayleighDamping\(alpha=([0-9.]+), beta=([0-9.e-]+)\)", "damping")
lo, hi, nf = need(r"np\.linspace\(([0-9.]+), ([0-9.]+), (\d+)\) \* np\.sqrt\(lam\[0\]\)", "frequency grid")
(npre,) = need(r"Vp = Vf\[:, :(\d+)\]", "pre-reduction size")
assert int(n_el) == A.N_EL and float(al) == A.ALPHA and float(be) == A.BETA, "listing and constants disagree on the beam"
assert (float(lo), float(hi), int(nf)) == (A.BAND_LO, A.BAND_HI, A.N_FREQ), "listing and constants disagree on the band"
assert int(npre) == A.N_PRE, "listing and constants disagree on the pre-reduction"


def f(x):
    return f"{x:g}"


exp = int(f"{A.BETA:.0e}".split("e")[1])
C = {"cbtNEl": str(A.N_EL), "cbtAlpha": f(A.ALPHA), "cbtBeta": f"10^{{{exp}}}", "cbtNFreq": str(A.N_FREQ),
     "cbtBandLo": f(A.BAND_LO), "cbtBandHi": f(A.BAND_HI), "cbtBandExt": f(A.EXT_HI), "cbtBandFar": f(A.FAR_LO),
     "cbtOrderMax": str(2 * A.N_PRE - 2)}
with open(os.path.join(BOOK, "tables", "numbers_ch09_const.tex"), "w") as fh:
    fh.write("% generated by scripts/ch09_consts.py -- do not edit\n")
    for k, v in C.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
print(C)
