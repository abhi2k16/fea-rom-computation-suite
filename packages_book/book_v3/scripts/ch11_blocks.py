"""Structure of the reduced stiffness and mass matrices (Chapter 11, Sec. 11.3, item C2).
Run: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_blocks.py
Writes figures/ch11_blocks.pdf and tables/numbers_ch11_blocks.tex (macro prefix ccm)."""
import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from rom_engine.cms import couple, craig_bampton, guyan
plt.rcParams.update({"font.size": 8})
NEL = a.NEL; NUM = {}
fr, K, M = a.beam(1.0, 2 * NEL, [0, 2 * NEL])
frL, KL, ML = a.beam(0.5, NEL, [0]); frR, KR, MR = a.beam(0.5, NEL, [NEL])
pos = lambda f_, d: int(np.where(f_ == d)[0][0])
ibL = [pos(frL, 2 * NEL), pos(frL, 2 * NEL + 1)]; ibR = [pos(frR, 0), pos(frR, 1)]
nm = 5
cl, cr = craig_bampton(KL, ML, ibL, nm), craig_bampton(KR, MR, ibR, nm)
cp = couple([cl, cr], [[0, 1], [0, 1]])
vd = np.arange(0, K.shape[0], 2)
idx = vd[np.round(np.linspace(0, len(vd) - 1, 14)[1:-1]).astype(int)]
g = guyan(K, M, idx)
def rel(A):                                  # scale-free coupling |a_ij| / sqrt(a_ii a_jj)
    d = np.sqrt(np.abs(np.diag(A))); return np.abs(A) / np.outer(d, d)
TOL = 1e-9
cols = [("one half, $n_m=5$", cl.K, cl.M, 2), ("two halves coupled", cp.K, cp.M, 2), ("Guyan, 12 masters", g.K, g.M, None)]
fig, ax = plt.subplots(2, 3, figsize=(6.2, 4.3), constrained_layout=True)
for j, (t, Kx, Mx, nb) in enumerate(cols):
    for i, (A, nmn) in enumerate(((Kx, "stiffness"), (Mx, "mass"))):
        R = rel(A); L = np.log10(np.maximum(R, 1e-12))
        im = ax[i, j].imshow(L, cmap="viridis_r", vmin=-12, vmax=0)
        ax[i, j].set_xticks([]); ax[i, j].set_yticks([])
        if nb:
            ax[i, j].axhline(nb - 0.5, color="w", lw=0.8); ax[i, j].axvline(nb - 0.5, color="w", lw=0.8)
            if j == 1:
                for off in (nb + nm,): ax[i, j].axhline(off - 0.5, color="w", lw=0.8); ax[i, j].axvline(off - 0.5, color="w", lw=0.8)
        if i == 0: ax[i, j].set_title(t, fontsize=8)
        if j == 0: ax[i, j].set_ylabel(nmn)
        NUM[f"ccmBlk{['Half','Coupled','Guyan'][j]}{'K' if i == 0 else 'M'}Nnz"] = str(int((R > TOL).sum()))
        NUM[f"ccmBlk{['Half','Coupled','Guyan'][j]}Size"] = str(A.shape[0])
cb = fig.colorbar(im, ax=ax, shrink=0.8, pad=0.02); cb.set_label("$\\log_{10}\\,|a_{ij}|/\\sqrt{a_{ii}a_{jj}}$")
fig.savefig(os.path.join(FIG, "ch11_blocks.pdf")); fig.savefig("/tmp/ch11_blocks.png", dpi=140)
nb = 2
NUM["ccmBlkCoupling"] = f"{100 * np.linalg.norm(cl.M[nb:, :nb]) / np.linalg.norm(cl.M):.0f}"
NUM["ccmBlkModalId"] = "1"
NUM["ccmBlkNm"] = str(nm)
NUM["ccmBlkTotalSq"] = str(cp.K.shape[0] ** 2)
with open(os.path.join(TAB, "numbers_ch11_blocks.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_blocks.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
