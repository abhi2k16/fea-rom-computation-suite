"""
ch03_listings.py -- runs the bar listing of Chapter 3 (label lst:el-bar) and saves its output and the total mass for the book.

The code is read from chapters/ch03.tex, so the printed output cannot drift from the listed code.
Writes: tables/ch03_bar_out.txt, tables/numbers_ch03_listing.tex.   Run from the book directory:   python scripts/ch03_listings.py
"""
__author__ = "Abhijeet <abhijeetshandilya19@gmail.com>"
import io, os, re, sys, contextlib, warnings
warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
p = os.path.join(BOOK, "..", "..", "fea_engine", "src")
if os.path.isdir(p): sys.path.insert(0, os.path.abspath(p))
src = open(os.path.join(BOOK, "chapters", "ch03.tex"), encoding="utf-8").read()
code = re.search(r"\\begin\{lstlisting\}\[[^\]]*label=\{lst:el-bar\}\]\n(.*?)\\end\{lstlisting\}", src, re.S).group(1)
ns = {"__name__": "__listing__"}
buf = io.StringIO()
with contextlib.redirect_stdout(buf):
    exec(compile(code, "lst:el-bar", "exec"), ns)
open(os.path.join(BOOK, "tables", "ch03_bar_out.txt"), "w", encoding="utf-8").write(buf.getvalue())
mass = ns["rho"] * ns["A"] * ns["L"]
with open(os.path.join(BOOK, "tables", "numbers_ch03_listing.tex"), "w") as fh:
    fh.write("% generated by scripts/ch03_listings.py -- do not edit\n")
    fh.write(f"\\newcommand{{\\cecBarMass}}{{{mass:.2f}\\xspace}}\n")
print(buf.getvalue())
