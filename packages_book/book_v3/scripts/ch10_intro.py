"""Chapter 10 introduction figure (Section 10.1): figures/ch10_intro.pdf and tables/numbers_ch10_intro.tex.

Beam of the chapter (greedy_frequency_training.build_damped_cantilever, 20 elements, 40 unknowns, Rayleigh alpha=2,
beta=1e-5, tip force). Panels: (a) tip response with half-power bands and five evenly spaced snapshot frequencies;
(b) singular values of the 400-frequency snapshot matrix; (c) sigma_min(A(w))."""
import os, warnings
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh
from greedy_frequency_training import build_damped_cantilever
warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
BLUE, VIOLET, GREY, ORANGE = "#08519c", "#54278f", "#636363", "#d95f0e"
plt.rcParams.update({"font.size": 8, "axes.titlesize": 8.5, "axes.labelsize": 8, "legend.fontsize": 7,
                     "axes.grid": True, "grid.alpha": 0.3})
NUM = {}
num = lambda k, v: NUM.__setitem__(k, v)

s, al, be = build_damped_cantilever(n=20)
fr = np.asarray(s.free_dofs); ix = np.ix_(fr, fr)
K, M, C = s.K[ix], s.M[ix], s.C[ix]
lam, _ = eigh(K, M); wn = np.sqrt(lam); w1 = wn[0]; zeta = 0.5 * (al / wn + be * wn)
F = np.zeros(s.n_dof); F[s.n_dof - 2] = 1000.0; tip = len(fr) - 2
LO, HI, NS = 0.1, 20.0, 400
band = np.linspace(LO, HI, NS)
fine = np.unique(np.concatenate([np.linspace(LO, HI, 4000)] + [wn[k] / w1 + np.linspace(-1, 1, 801) * 6 * zeta[k] * wn[k] / w1
                                                           for k in range(3)]))
fine = fine[(fine >= LO) & (fine <= HI)]
x = lambda r: s.solve_harmonic(r * w1, F)[fr]
amp = np.array([abs(x(r)[tip]) for r in fine])
X = np.array([x(r) for r in band]).T
sv = np.linalg.svd(X, compute_uv=False); rel = sv / sv[0]
smin = np.array([np.linalg.svd(-(r * w1) ** 2 * M + 1j * r * w1 * C + K, compute_uv=False)[-1] for r in fine])
wid = 2 * zeta[:3] * wn[:3] / w1                      # half-power width in units of w1
even5 = np.linspace(LO, HI, 5)
miss = [np.min(np.abs(even5 - wn[k] / w1)) / wid[k] for k in range(3)]

fig, ax = plt.subplots(1, 3, figsize=(7.4, 2.6), constrained_layout=True)
a = ax[0]
a.semilogy(fine, amp, color=BLUE, lw=1.0)
for k in range(3):
    a.axvspan(wn[k] / w1 - wid[k] / 2, wn[k] / w1 + wid[k] / 2, color=ORANGE, alpha=0.5, lw=0)
    a.text(wn[k] / w1, amp.max() * (1.6 if k == 0 else 0.6), f"{k + 1}", ha="center", fontsize=7, color=ORANGE)
for e in even5:
    a.axvline(e, color=GREY, lw=0.7, ls=":")
a.set_ylim(amp.min() * 0.5, amp.max() * 6)
a.set_xlabel(r"$\omega/\omega_1$"); a.set_ylabel(r"$|x_{\rm tip}(\omega)|$ (m)")
a.set_title("(a) tip response", loc="left")
a = ax[1]
a.semilogy(np.arange(1, 31), rel[:30], "o-", color=VIOLET, ms=3, lw=0.8)
a.axhline(1e-6, color=GREY, lw=0.7, ls="--")
a.set_ylim(1e-18, 3)
a.set_xlabel("index $j$"); a.set_ylabel(r"$\sigma_j/\sigma_1$ of the snapshots")
a.set_title("(b) snapshot singular values", loc="left")
a = ax[2]
a.semilogy(fine, smin, color=BLUE, lw=1.0)
for k in range(3):
    a.axvline(wn[k] / w1, color=ORANGE, lw=0.7, alpha=0.6)
a.set_xlabel(r"$\omega/\omega_1$"); a.set_ylabel(r"$\sigma_{\min}(\boldsymbol{A}(\omega))$")
a.set_title(r"(c) smallest singular value of $\boldsymbol{A}$", loc="left")
fig.savefig(os.path.join(BOOK, "figures", "ch10_intro.pdf"))

num("cfrIntroNMode", str(int((wn <= HI * w1).sum())))
num("cfrIntroZetaOne", f"{100 * zeta[0]:.2f}")
for i, nm in enumerate(("One", "Two", "Three")):
    num("cfrIntroWidth" + nm, f"{wid[i]:.3g}")
    num("cfrIntroMiss" + nm, f"{miss[i]:.2g}")
num("cfrIntroFracBand", f"{100 * wid.sum() / (HI - LO):.0f}")
num("cfrIntroEvenStep", f"{even5[1] - even5[0]:.2f}")
num("cfrIntroNSnap", str(NS))
num("cfrIntroRankSix", str(int((rel > 1e-6).sum())))
num("cfrIntroRankNine", str(int((rel > 1e-9).sum())))
num("cfrIntroSvTwenty", f"{rel[19]:.0e}".replace("e-", "\\times10^{-") + "}")
num("cfrIntroSminRatio", f"{smin.max() / smin.min():.1e}")
num("cfrIntroAmpRatio", f"{amp.max() / amp.min():.1e}")
num("cfrIntroSminLow", f"{smin.min():.0f}")
imin = int(np.argmin(smin)); num("cfrIntroSminAt", f"{fine[imin]:.2f}")
with open(os.path.join(BOOK, "tables", "numbers_ch10_intro.tex"), "w") as fh:
    fh.write("% generated by scripts/ch10_intro.py -- do not edit\n")
    for k_, v in NUM.items():
        fh.write(f"\\newcommand{{\\{k_}}}{{{v}\\xspace}}\n")
print(NUM)
