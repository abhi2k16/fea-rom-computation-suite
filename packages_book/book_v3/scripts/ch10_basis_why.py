"""B1 (PLAN_ch10_math.md): why a few snapshots suffice. The response of the beam as a sum over modes
x(w) = sum_l phi_l f_l / (theta_1(w) + theta_2(w) w_l^2), the 'resonant modes + static tail' subspace, and its distance
to the 400-snapshot matrix against the first k modes and against the POD (optimal). Euclidean norms, as in Section 10.1.
figures/ch10_math_basis.pdf, tables/numbers_ch10_basis_why.tex. Snapshots from the modal sum (no ill-conditioned solve)."""
import os, warnings
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh, subspace_angles
from greedy_frequency_training import build_damped_cantilever
warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE)
BLUE, VIOLET, GREY, ORANGE = "#08519c", "#54278f", "#636363", "#d95f0e"
plt.rcParams.update({"font.size": 7.5, "axes.titlesize": 8, "axes.labelsize": 7.5, "axes.grid": True, "grid.alpha": 0.3})
NUM = {}
num = lambda k, v: NUM.__setitem__(k, v)


def tex(v, p=1):
    m, e = f"{v:.{p}e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


s, al, be = build_damped_cantilever(n=20)
fr = np.asarray(s.free_dofs); ix = np.ix_(fr, fr)
K, M = s.K[ix], s.M[ix]
lam, Phi = eigh(K, M); wn = np.sqrt(lam); w1 = wn[0]
F = np.zeros(s.n_dof); F[s.n_dof - 2] = 1000.0; Ff = F[fr]; f = Phi.T @ Ff
NM = 3                                              # resonances in the band
om = np.linspace(0.1, 20.0, 400) * w1
th1 = -om ** 2 + 1j * om * al; th2 = 1 + 1j * om * be
Dl = th1[None, :] + th2[None, :] * wn[:, None] ** 2          # = w_l^2 - w^2 + 2 i zeta_l w_l w
X = Phi @ (f[:, None] / Dl)
nx = np.linalg.norm(X)
sv = np.linalg.svd(X, compute_uv=False)
U = np.linalg.svd(X, full_matrices=False)[0]


def dist(B):
    Q, _ = np.linalg.qr(B.astype(complex))
    return np.linalg.norm(X - Q @ (Q.conj().T @ X)) / nx


tails = [Phi[:, NM:] @ (f[NM:] / wn[NM:] ** (2 * (j + 1))) for j in range(6)]
dims = np.arange(1, 10)
e_mod = [dist(Phi[:, :k]) for k in dims]
e_tail = [dist(np.column_stack([Phi[:, :NM]] + tails[:k - NM])) if k >= NM else np.nan for k in dims]
e_pod = [dist(U[:, :k]) for k in dims]
t0_static = np.linalg.solve(K, Ff) - Phi[:, :NM] @ (f[:NM] / wn[:NM] ** 2)
fig, ax = plt.subplots(1, 3, figsize=(6.2, 2.8), constrained_layout=True)
a = ax[0]
c = np.abs(f[:, None] / Dl); c /= c[0].max()
cols = plt.cm.viridis(np.linspace(0, 0.9, 6))
for l in range(6):
    a.semilogy(om / w1, c[l], color=cols[l], lw=1.0, label=f"mode {l + 1}")
a.set_xlabel(r"$\omega/\omega_1$"); a.set_ylabel(r"$|\phi_\ell^T F/D_\ell|$, relative to the peak of mode 1")
a.set_ylim(1e-9, 3); a.legend(fontsize=6, ncol=2, loc="lower left"); a.set_title("(a) modal content of the response", loc="left")
a = ax[1]
a.semilogy(dims, e_mod, "o-", color=GREY, ms=3, lw=0.9, label="first $k$ modes")
a.semilogy(dims, e_tail, "s-", color=ORANGE, ms=3, lw=0.9, label="3 modes + $k-3$ static terms")
a.semilogy(dims, e_pod, "^--", color=VIOLET, ms=3, lw=0.9, label="POD (best possible)")
a.set_xlabel("dimension $k$"); a.set_ylabel("relative distance of the snapshots"); a.legend(fontsize=6, loc="upper right")
a.set_title("(b) subspace of dimension $k$", loc="left")
a = ax[2]
B = np.column_stack([Phi[:, :NM]] + tails[:5]); Qb, _ = np.linalg.qr(B)
ov = np.abs(U[:, :8].conj().T @ Qb[:, :8])
im = a.imshow(ov, cmap="Blues", vmin=0, vmax=1, aspect="equal", origin="upper")
a.set_xticks(range(8)); a.set_xticklabels(["$\\phi_1$", "$\\phi_2$", "$\\phi_3$", "$t_0$", "$t_1$", "$t_2$", "$t_3$", "$t_4$"], fontsize=6.5)
a.set_yticks(range(8)); a.set_yticklabels(range(1, 9)); a.grid(False)
a.set_xlabel("modes and static terms (orthonormalised)"); a.set_ylabel("POD direction"); a.set_title("(c) overlap", loc="left")
fig.colorbar(im, ax=a, shrink=0.8, pad=0.02)
fig.savefig(os.path.join(BOOK, "figures", "ch10_math_basis.pdf"))
num("cfrBoneNFree", str(len(Ff)))
for k, kn in ((4, "Four"), (5, "Five"), (7, "Seven")):
    num(f"cfrBoneMod{kn}", tex(e_mod[k - 1])); num(f"cfrBoneTail{kn}", tex(e_tail[k - 1])); num(f"cfrBonePod{kn}", tex(e_pod[k - 1]))
num("cfrBoneModThree", tex(e_mod[2]))
num("cfrBoneStaticDiff", tex(np.linalg.norm(t0_static - tails[0]) / np.linalg.norm(t0_static)))
ang = subspace_angles(U[:, :NM], Phi[:, :NM]); num("cfrBoneAngThree", f"{np.degrees(ang.max()):.1f}")
num("cfrBoneRatioFive", f"{e_mod[4] / e_tail[4]:.0f}")
num("cfrBoneOvMin", f"{np.min(np.diag(ov)):.3f}")
num("cfrBoneRatioSeven", tex(e_mod[6] / e_tail[6], 0))
num("cfrBoneSv", ", ".join(f"{v / sv[0]:.1e}" for v in sv[:8]))
num("cfrBoneModalTwo", tex(c[1].max())); num("cfrBoneModalThree", tex(c[2].max())); num("cfrBoneModalFour", tex(c[3].max()))
with open(os.path.join(BOOK, "tables", "numbers_ch10_basis_why.tex"), "w") as fh:
    fh.write("% generated by scripts/ch10_basis_why.py -- do not edit\n")
    for k_, v in NUM.items():
        fh.write(f"\\newcommand{{\\{k_}}}{{{v}\\xspace}}\n")
print(NUM)
print("OV diag", np.round(np.diag(ov), 3))
