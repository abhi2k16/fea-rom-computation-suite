"""Run Listing 9.2 of Chapter 9 (lst:bt-try) and write its printed output and the numbers quoted around it.

The code is read from chapters/ch09.tex, so the printed output cannot drift from the listed code.
Writes tables/ch09_try_out.txt and tables/numbers_ch09_try.tex."""
import io, os, re, sys, contextlib, warnings
import numpy as np
warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__)); BOOK = os.path.dirname(HERE); ROOT = os.path.abspath(os.path.join(BOOK, "..", ".."))
sys.path[:0] = [ROOT, os.path.join(ROOT, "rom_engine", "examples")]
src = open(os.path.join(BOOK, "chapters", "ch09.tex"), encoding="utf-8").read()


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


m = re.search(r"\\begin\{lstlisting\}\[[^\]]*label=\{lst:bt-try\}\]\n(.*?)\\end\{lstlisting\}", src, re.S)
g = {"__name__": "__listing__"}
buf = io.StringIO()
with contextlib.redirect_stdout(buf):
    exec(compile(m.group(1), "lst:bt-try", "exec"), g)
open(os.path.join(BOOK, "tables", "ch09_try_out.txt"), "w", encoding="utf-8").write(buf.getvalue())
print(buf.getvalue())

H, omegas, bt, kr = g["H"], g["omegas"], g["bt"], g["kr"]
peak = np.max(np.abs(H))
err = lambda mdl: np.max(np.abs(mdl.frequency_response(omegas) - H)) / peak
bound = bt.h_infinity_error_bound()
out = buf.getvalue()
t_red = [float(x) for x in re.findall(r"sweep\s+([\d.]+) ms", out)]
t_full = float(re.search(r"frequencies\): (\d+) ms", out).group(1))
NUM = {"cbtTryErrBt": sci(err(bt)), "cbtTryErrKry": sci(err(kr)), "cbtTryBoundRel": sci(bound / peak),
       "cbtTryGap": f"{bound / peak / err(bt):.0f}", "cbtTryPeak": sci(peak),
       "cbtTryFullMs": f"{t_full:.0f}", "cbtTryGainSweep": f"{t_full / np.mean(t_red):.0f}"}
with open(os.path.join(BOOK, "tables", "numbers_ch09_try.tex"), "w") as fh:
    fh.write("% generated by scripts/ch09_listings.py -- do not edit\n")
    for k, v in NUM.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
print(NUM)
