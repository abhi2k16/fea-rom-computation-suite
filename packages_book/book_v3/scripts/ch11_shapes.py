"""Mode-shape error of Guyan and Craig-Bampton models at equal size (Chapter 11, Sec. 11.5.1, item C5).
Run: PYTHONPATH=fea_engine/src:rom_engine/src python packages_book/book_v3/scripts/ch11_shapes.py
Writes figures/ch11_shapes.pdf and tables/numbers_ch11_shapes.tex (macro prefix ccm)."""
import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.linalg import eigh
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch11_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from rom_engine.cms import couple, craig_bampton, guyan
plt.rcParams.update({"font.size": 8, "axes.grid": True, "grid.alpha": 0.3})
NEL = a.NEL; NUM = {}
def sci(x):
    m, e = f"{x:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"
fr, K, M = a.beam(1.0, 2 * NEL, [0, 2 * NEL]); w2, Vf = eigh(K, M)
frL, KL, ML = a.beam(0.5, NEL, [0]); frR, KR, MR = a.beam(0.5, NEL, [NEL])
pos = lambda f_, d: int(np.where(f_ == d)[0][0])
ibL = [pos(frL, 2 * NEL), pos(frL, 2 * NEL + 1)]; ibR = [pos(frR, 0), pos(frR, 1)]
nm = 5
cp = couple([craig_bampton(KL, ML, ibL, nm), craig_bampton(KR, MR, ibR, nm)], [[0, 1], [0, 1]])
vd = np.arange(0, K.shape[0], 2)
idx = vd[np.round(np.linspace(0, len(vd) - 1, 14)[1:-1]).astype(int)]
g = guyan(K, M, idx)
nfull = K.shape[0]; pos_full = {d: i for i, d in enumerate(fr)}
def full_shape(x):
    uL, uR = cp.expand(0, x), cp.expand(1, x); u = np.zeros(nfull)
    for d, val in zip(frL, uL): u[pos_full[d]] = val
    for d, val in zip(frR, uR):
        if d + 2 * NEL in pos_full: u[pos_full[d + 2 * NEL]] = val
    return u
_, X = cp.solve_modal(8); _, Xg = eigh(g.K, g.M)
mac = lambda u, v: abs(u @ M @ v) ** 2 / ((u @ M @ u) * (v @ M @ v))
shapes = {"cb": [full_shape(X[:, k]) for k in range(8)], "guyan": [g.expand(Xg[:, k]) for k in range(8)]}
err = {m_: np.array([1 - mac(Vf[:, k], shapes[m_][k]) for k in range(8)]) for m_ in shapes}
words = ["One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight"]
for m_, tag in (("cb", "Cb"), ("guyan", "Guyan")):
    for k in range(8): NUM[f"ccmSh{tag}{words[k]}"] = sci(err[m_][k])
NUM["ccmShRatioFour"] = f"{err['guyan'][3] / err['cb'][3]:.0f}"; NUM["ccmShRatioEight"] = f"{err['guyan'][7] / err['cb'][7]:.0f}"
NUM["ccmShGuyWins"] = ", ".join(str(k + 1) for k in range(8) if err["guyan"][k] < err["cb"][k])
NUM["ccmShGuyWinsCount"] = str(int((err["guyan"] < err["cb"]).sum()))
NUM["ccmShGuyWinsCountComp"] = str(int((err["guyan"] >= err["cb"]).sum()))
xs = np.arange(1, NEL * 2) * (1.0 / (2 * NEL))                 # transverse dofs at the nodes between the clamps
def pointwise(mode):
    ue = Vf[:, mode]; out = {}
    for m_ in shapes:
        ur = shapes[m_][mode]; c = (ue @ M @ ur) / (ur @ M @ ur)
        out[m_] = (ue - c * ur)[vd] / np.abs(ue[vd]).max()
    return out
fig, ax = plt.subplots(1, 3, figsize=(6.2, 2.5), constrained_layout=True)
ks = np.arange(1, 9)
ax[0].semilogy(ks, err["guyan"], "s--", color="C1", ms=3.5, label="Guyan, 12 masters"); ax[0].semilogy(ks, err["cb"], "o-", color="C0", ms=3.5, label="Craig--Bampton, 12 unknowns")
ax[0].set_xlabel("mode number"); ax[0].set_ylabel("$1-\\mathrm{MAC}$"); ax[0].set_title("(a) shape error", loc="left", fontsize=8); ax[0].legend(fontsize=5.5, loc="lower right")
for j, mode in ((1, 3), (2, 7)):
    e = pointwise(mode)
    ax[j].plot(xs, e["guyan"], "C1--", lw=1.0, label="Guyan"); ax[j].plot(xs, e["cb"], "C0-", lw=1.0, label="Craig--Bampton")
    ax[j].axvline(0.5, color="0.6", ls=":", lw=0.8)
    ax[j].set_xlabel("position along the beam"); ax[j].set_title(f"({'bc'[j - 1]}) error of mode {mode + 1}", loc="left", fontsize=8)
    ax[j].ticklabel_format(axis="y", style="sci", scilimits=(0, 0)); ax[j].tick_params(axis="y", labelsize=6)
ax[1].legend(fontsize=5.5, loc="upper left")
ax[1].set_ylabel("shape error / peak of the mode")
fig.savefig(os.path.join(FIG, "ch11_shapes.pdf")); fig.savefig("/tmp/ch11_shapes.png", dpi=140)
with open(os.path.join(TAB, "numbers_ch11_shapes.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_shapes.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
