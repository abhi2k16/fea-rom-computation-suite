"""Counts for the component-POD workflow diagram (Chapter 11, item C7).
The counts are read from scripts/ch11_assets.py (snapshot count, ranks, interface coefficients), not retyped.
Run: python3 packages_book/book_v3/scripts/ch11_workflow.py ; writes tables/numbers_ch11_workflow.tex (prefix ccm)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); TAB = os.path.join(HERE, "..", "tables")
src = open(os.path.join(HERE, "ch11_assets.py")).read()
snap = int(re.search(r"component_snapshots\(wrap\(fa\), (\d+), (\d+)", src).group(2))
npar = int(re.search(r"component_snapshots\(wrap\(fa\), (\d+), (\d+)", src).group(1))
ranks = [int(x) for x in re.search(r"for r in \(([\d, ]+)\):", src).group(1).split(",")]
ncoef = int(re.search(r"G2 @ p\[:(\d+)\]", src).group(1))
assert npar == ncoef + 1
names = ["A", "B", "C"]
NUM = {"ccmWfSnap": snap, "ccmWfCoef": ncoef}
for n, r in zip(names, ranks):
    NUM[f"ccmWfRank{n}"] = r; NUM[f"ccmWfUnk{n}"] = 2 * r
with open(os.path.join(TAB, "numbers_ch11_workflow.tex"), "w") as fh:
    fh.write("% generated by scripts/ch11_workflow.py -- do not edit\n")
    for k, v in NUM.items(): fh.write("\\newcommand{\\%s}{%s\\xspace}\n" % (k, v))
print(NUM)
