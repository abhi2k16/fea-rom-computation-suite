import os, importlib.util
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch
from scipy.integrate import solve_ivp
HERE = os.path.dirname(os.path.abspath(__file__)); FIG = os.path.join(HERE, "..", "figures"); TAB = os.path.join(HERE, "..", "tables")
spec = importlib.util.spec_from_file_location("a", os.path.join(HERE, "ch12_assets.py")); a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
from rom_engine.nonlinear_rom import PolynomialModalROM, MultiFidelitySurrogate, AppliedLoadStrategy
from rom_engine.nnm import HarmonicBalanceSystem, solve_nnm_backbone
plt.rcParams.update({"font.size": 7, "axes.grid": True, "grid.alpha": 0.3})
NUM = {}

# ---- beam (as in Sec. 12.4): 16 elements, 3 modes, 45 training solves, central load to 6000 N
N_ELEM, N_MODES, N_TRAIN, LMAX, SPAN = 16, 3, 45, 6000.0, 1.0
fx = a.clamped(N_ELEM, N_MODES); V, M, f, free = fx["V"], fx["M_ff"], fx["freq_hz"], fx["free_dofs"]
Lam = (2 * np.pi * f) ** 2; mid = list(free).index((N_ELEM // 2) * 3 + 1)
st = AppliedLoadStrategy((0.3, 3.0), 0.01, N_TRAIN, np.random.default_rng(0))
ql, qn, F = st.generate(V, M, f, fx["mode_shape_peaks"], fx["fom_solver"])
ice = PolynomialModalROM(N_MODES).fit(qn, F); mfs = MultiFidelitySurrogate().fit(ql, F)
sh = np.zeros(len(free)); sh[mid] = -1; fh = V.T @ sh
loads = np.linspace(0, LMAX, 13); Mf, Mi, Mm, Ml = [], [], [], []; qp = np.zeros(N_MODES)
for P in loads:
    Mf.append(fx["fom_solver"](P * sh, n_steps=30)[mid])
    q, _ = ice.predict(F_ext=P * fh, Lambda=Lam, q0=qp); qp = q; Mi.append((V @ q)[mid])
    Mm.append((V @ mfs.reconstruct_q_nl(P * fh / Lam, Lam))[mid]); Ml.append((V @ (P * fh / Lam))[mid])
Mf, Mi, Mm, Ml = [-1000 * np.array(x) for x in (Mf, Mi, Mm, Ml)]

# ---- oscillator of Listing 12.x: q'' + lam q + k3 q^3 = 0 released at rest from q = amp
lam, k3, amp = 100.0, 5.0e4, 0.03
def measured(x):
    stop = lambda t, y: y[1]; stop.direction = 1
    s = solve_ivp(lambda t, y: [y[1], -lam * y[0] - k3 * y[0] ** 3], [0, 5 * 2 * np.pi / np.sqrt(lam)], [x, 0.0], events=stop, rtol=1e-12, atol=1e-14)
    return 2 * np.pi / np.mean(np.diff(s.t_events[0]))
class Cubic:
    def predict(self, q): return k3 * np.asarray(q) ** 3
    def jacobian(self, q): return np.diag(3 * k3 * np.asarray(q) ** 2)
hb = HarmonicBalanceSystem(np.array([lam]), n_harmonics=1, n_time_samples=128)
amps, om, Z, ok = solve_nnm_backbone(hb, Cubic(), (0.005, amp), n_points=12, domain="q_nl")
peak = Z[:, 0, 0] + Z[:, 1, 0]
Ad = np.linspace(0.005, amp, 6); wd = np.array([measured(x) for x in Ad])
w_meas = measured(amp); w_lin = np.sqrt(lam)

# ---- macros
def put(k, v): NUM[k] = v
put("cniLam", f"{lam:g}"); put("cniCubic", "5\\times10^{4}"); put("cniAmp", f"{amp:g}")
put("cniWlin", f"{w_lin:.2f}"); put("cniWmeas", f"{w_meas:.2f}"); put("cniMissPct", f"{100 * abs(w_lin - w_meas) / w_meas:.0f}")
put("cniNTrain", f"{N_TRAIN}"); put("cniSpan", f"{SPAN:g}"); put("cniModes", f"{N_MODES}")
put("cniLinMissPct", f"{100 * abs(Ml[-1] - Mf[-1]) / abs(Mf[-1]):.0f}")
with open(os.path.join(TAB, "numbers_ch12_intro.tex"), "w") as fh:
    fh.write("% generated by scripts/ch12_intro.py -- do not edit\n")
    for k, v in NUM.items(): fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")

# ---- figure
fig = plt.figure(figsize=(6.3, 2.7)); gs = fig.add_gridspec(1, 3, width_ratios=[1.9, 1, 1])
ax = fig.add_subplot(gs[0]); ax.axis("off"); ax.set_xlim(0, 10); ax.set_ylim(0, 10); ax.set_title("(a) visible and learned", fontsize=7)
def box(x, y, w, h, t, fc, fs=6.5):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.05", fc=fc, ec="k", lw=.8)); ax.text(x + w / 2, y + h / 2, t, ha="center", va="center", fontsize=fs)
box(.2, 3.6, 2.2, 2.8, "solver\n(black box)\n$K, M, f_{nl}$\nnot visible", "0.85")
rows = [("Loewner", "responses at one dof", "frequencies,\ndamping"), ("operator inference", "states, accel., forces", "reduced\n$M$, $K$"),
        ("hybrid modal ROM", "full-order static solves", "restoring\nforce"), ("harmonic balance", "a model of $f_{nl}$", "backbone")]
for i, (m, d, l) in enumerate(rows):
    y = 8.0 - i * 2.2
    box(3.3, y - .6, 3.7, 1.2, f"{m}\n{d}", "#dbe9f6", 5.5); box(7.7, y - .6, 2.2, 1.2, l, "#fde8c8", 5.5)
    ax.add_patch(FancyArrowPatch((2.5, 5), (3.2, y), arrowstyle="->", mutation_scale=8)); ax.add_patch(FancyArrowPatch((7.05, y), (7.65, y), arrowstyle="->", mutation_scale=8))
ax.text(5.15, 9.7, "data in", fontsize=6.5, ha="center"); ax.text(8.75, 9.7, "learned", fontsize=6.5, ha="center")
b = fig.add_subplot(gs[1])
b.plot(loads, Mf, "ko-", ms=4, label="full order"); b.plot(loads, Ml, "C3:", label="linear"); b.plot(loads, Mi, "C0--", label="polynomial (ICE)"); b.plot(loads, Mm, "C1-.", label="RBF")
b.set_xlabel("central load (N)"); b.set_ylabel("mid-span deflection (mm)"); b.legend(fontsize=6); b.set_title("(b) beam stiffens", fontsize=7)
c = fig.add_subplot(gs[2])
c.axhline(w_lin, color="C3", ls=":", label="linear"); c.plot(peak, om, "C0-", label="HB, 1 harmonic"); c.plot(Ad, wd, "ko", ms=4, label="time integration")
c.set_xlabel("release amplitude"); c.set_ylabel("frequency (rad/s)"); c.legend(fontsize=6); c.set_title("(c) oscillator frequency", fontsize=7)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "ch12_intro.pdf")); print({k: v for k, v in NUM.items()})
