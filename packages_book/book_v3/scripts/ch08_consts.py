"""Chapter 8: the design constants quoted in the text, as macros (tables/numbers_ch08_const.tex).

Every value comes from the place that uses it: the constants block of ch08_assets.py, the listings and prose of
ch08.tex (the Try-it listing), the example script (load noise) and the package (default iterations of optimal_lhs).
A mismatch between a constant and the listing it describes stops the run."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import ch08_assets as A

BOOK = A.BOOK
tex = open(os.path.join(BOOK, "chapters", "ch08.tex"), encoding="utf-8").read()
figsrc = open(os.path.join(HERE, "ch08_figs.py"), encoding="utf-8").read()
exsrc = open(os.path.join(A.ROOT, "rom_engine", "examples", "two_region_beam_rom.py"), encoding="utf-8").read()
smp = open(os.path.join(A.ROOT, "rom_engine", "src", "rom_engine", "sampling.py"), encoding="utf-8").read()

def grab(rx, s, what):
    m = re.search(rx, s)
    if not m:
        raise SystemExit(f"ch08_consts: cannot find {what}")
    return m.groups()

(n_query,) = grab(r"uniform\(0\.5, 5\.0, size=\((\d+), 2\)\)", tex, "number of queries in the Try-it listing")
n_train, n_modes = grab(r"build_rom\(model, n_train=(\d+), n_modes=(\d+)\)", tex, "n_train and n_modes in the Try-it listing")
(n_elem,) = grab(r"build_two_region_beam\(n=(\d+)\)", tex, "n in the Try-it listing")
(noise,) = grab(r"abs\(tip_load\) \* ([0-9.]+), size", exsrc, "load noise in build_rom")
(n_iter,) = grab(r"n_iter=(\d+)", smp, "n_iter default of optimal_lhs")
(npairs,) = grab(r"BEAM_NPAIRS = (\d+)", figsrc, "BEAM_NPAIRS")
assert int(n_elem) == A.N_ELEM, "listing and constants disagree on the number of elements"

def f(x):
    return f"{x:g}"

C = {
    "cpdNElem": str(A.N_ELEM), "cpdMuLo": f(A.LO), "cpdMuHi": f(A.HI), "cpdXiLo": f(A.XI_LO), "cpdXiHi": f(A.XI_HI),
    "cpdTipLoad": f(abs(A.TIP_LOAD)), "cpdBeamNPairs": npairs,
    "cpdTryNQuery": n_query, "cpdTryNTrain": n_train, "cpdTryModes": n_modes, "cpdTryNoisePct": f(float(noise) * 100),
    "cpdDesN": str(A.DES_N), "cpdDesGridK": str(A.DES_GRID_K), "cpdOlhsTries": n_iter,
    "cpdSnapBasis": str(A.SNAP_CAP), "cpdSnapReps": str(A.SNAP_REPS), "cpdSnapNA": str(A.SNAP_NS[1]), "cpdSnapNB": str(A.SNAP_NS[3]),
    "cpdRulePct": f"{100 * (1 - A.RULE_GAP):.2f}", "cpdRuleThr": f"{1 - A.RULE_GAP:.4f}",
    "cpdRankA": str(A.RANK_A), "cpdRankB": str(A.RANK_B), "cpdRankC": str(A.RANK_C),
}
with open(os.path.join(BOOK, "tables", "numbers_ch08_const.tex"), "w") as fh:
    fh.write("% generated by scripts/ch08_consts.py -- do not edit\n")
    for k, v in C.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n")
print(C)
